const messages: Record<Locale, Record<MessageKey, string>> = { en, ru, ja, zh };

export function format(template: string, ...args: (string | number)[]): string {
  return template.replace(/\{(\d+)\}/g, (_, index) => String(args[Number(index)] ?? ""));
}

/** Translates a key for the currently selected language. Reads the reactive settings, so templates update on change. */
export function t(key: MessageKey, ...args: (string | number)[]): string {
  return format(messages[settings.language][key] ?? en[key], ...args);
}
